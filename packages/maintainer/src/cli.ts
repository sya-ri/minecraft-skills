export async function runMaintainerCli(argv: string[]): Promise<number> {
  const [command] = argv;
  if (!command || command === "help" || command === "--help" || command === "-h") {
    printHelp();
    return 0;
  }

  try {
    if (command === "ingest-java-manifest") {
      ingestJavaManifest(argv.slice(1));
      return 0;
    }

    if (command === "ingest-java-version-detail") {
      ingestJavaVersionDetail(argv.slice(1));
      return 0;
    }

    if (command === "ingest-java-version-details") {
      await ingestAllJavaVersionDetails(argv.slice(1));
      return 0;
    }

    if (command === "ingest-java-reports") {
      ingestJavaReports(argv.slice(1));
      return 0;
    }

    if (command === "generate-java-reports") {
      generateReports(argv.slice(1));
      return 0;
    }

    if (command === "ingest-paper-project") {
      ingestPaperProject(argv.slice(1));
      return 0;
    }

    if (command === "ingest-paper-builds") {
      await ingestAllPaperBuilds(argv.slice(1));
      return 0;
    }

    if (command === "ingest-paper-api-indexes") {
      await ingestAllPaperApiIndexes(argv.slice(1));
      return 0;
    }

    if (command === "ingest-vanilla-inventory") {
      ingestVanillaInventory(argv.slice(1));
      return 0;
    }

    if (command === "ingest-vanilla-inventories") {
      await ingestAllVanillaInventories(argv.slice(1));
      return 0;
    }

    if (command === "ingest-resourcepack-models") {
      ingestResourcepackModels(argv.slice(1));
      return 0;
    }

    if (command === "ingest-resourcepack-models-all") {
      await ingestAllResourcepackModels(argv.slice(1));
      return 0;
    }

    if (command !== "validate") {
      throw new Error(`Unknown command: ${command}`);
    }

    const result = validateRepository();
    if (!result.ok) {
      for (const message of result.messages) {
        console.error(message);
      }
      return 1;
    }
    console.log("minecraft-skills repository validation passed");
    return 0;
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    return 1;
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.exitCode = await runMaintainerCli(process.argv.slice(2));
}
