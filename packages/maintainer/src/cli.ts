function readOption(args: string[], name: string): string | undefined {
  const index = args.indexOf(name);
  if (index === -1) {
    return undefined;
  }
  return args[index + 1];
}

function ingestJavaManifest(args: string[]): void {
  const input = readOption(args, "--input");
  if (!input) {
    throw new Error("ingest-java-manifest requires --input <manifest.json>");
  }
  const retrievedAt = readOption(args, "--retrieved-at") ?? new Date().toISOString();
  const manifest = JSON.parse(readFileSync(input, "utf8")) as unknown;
  const versionIndex = buildJavaVersionIndex(manifest, retrievedAt);
  const root = findRepositoryRoot();
  const output = join(root, "packages/data/data/java/versions.json");
  writeFileSync(output, `${JSON.stringify(versionIndex, null, 2)}\n`);
  console.log(`wrote ${versionIndex.versions.length} Java 1.13+ releases to ${output}`);
}

function ingestJavaVersionDetail(args: string[]): void {
  const versionJsonPath = readOption(args, "--version-json");
  if (!versionJsonPath) {
    throw new Error("ingest-java-version-detail requires --version-json <version.json>");
  }
  const clientJarPath = readOption(args, "--client-jar");
  const versionJsonUrl = readOption(args, "--version-json-url");
  const retrievedAt = readOption(args, "--retrieved-at") ?? new Date().toISOString();
  const options: {
    versionJsonPath: string;
    clientJarPath?: string;
    versionJsonUrl?: string;
    retrievedAt: string;
  } = {
    versionJsonPath,
    retrievedAt,
  };
  if (clientJarPath) {
    options.clientJarPath = clientJarPath;
  }
  if (versionJsonUrl) {
    options.versionJsonUrl = versionJsonUrl;
  }
  const detail = buildJavaVersionDetail(options);
  const root = findRepositoryRoot();
  const output = join(root, `packages/data/data/java/version-details/${detail.version}.json`);
  writeFileSync(output, `${JSON.stringify(detail, null, 2)}\n`);
  console.log(`wrote Java ${detail.version} detail to ${output}`);
}

async function ingestAllJavaVersionDetails(args: string[]): Promise<void> {
  const root = findRepositoryRoot();
  const retrievedAt = readOption(args, "--retrieved-at") ?? new Date().toISOString();
  const written = await ingestJavaVersionDetails({
    root,
    retrievedAt,
    includeClientJars: !args.includes("--skip-client-jars"),
    force: args.includes("--force"),
    log: (message) => console.log(message),
  });
  console.log(`wrote ${written} Java version detail files`);
}

function ingestJavaReports(args: string[]): void {
  const version = readOption(args, "--version");
  if (!version) {
    throw new Error("ingest-java-reports requires --version <version>");
  }
  const reportsDir = readOption(args, "--reports-dir");
  if (!reportsDir) {
    throw new Error("ingest-java-reports requires --reports-dir <generated/reports>");
  }
  const retrievedAt = readOption(args, "--retrieved-at") ?? new Date().toISOString();
  const root = findRepositoryRoot();
  const detail = getVersionDetail("java", version);
  const summary = buildJavaReportsSummary({
    version: detail.version,
    reportsDir,
    serverJarUrl: readDownloadUrl(detail.downloads, "server"),
    retrievedAt,
  });
  writeJavaReportsSummary({
    root,
    version: detail.version,
    ...summary,
  });
  console.log(`wrote Java ${detail.version} reports summary and command paths`);
}

function generateReports(args: string[]): void {
  const serverJarPath = readOption(args, "--server-jar");
  if (!serverJarPath) {
    throw new Error("generate-java-reports requires --server-jar <server.jar>");
  }
  const workDir = readOption(args, "--work-dir");
  if (!workDir) {
    throw new Error("generate-java-reports requires --work-dir <dir>");
  }
  const outputDir = readOption(args, "--output-dir");
  if (!outputDir) {
    throw new Error("generate-java-reports requires --output-dir <dir>");
  }
  generateJavaReports({
    javaBin: readOption(args, "--java-bin") ?? "java",
    serverJarPath,
    workDir,
    outputDir,
  });
  console.log(`wrote generated Java reports to ${outputDir}`);
}

function ingestPaperProject(args: string[]): void {
  const projectJsonPath = readOption(args, "--project-json");
  if (!projectJsonPath) {
    throw new Error("ingest-paper-project requires --project-json <project.json>");
  }
  const latestBuildsJsonPath = readOption(args, "--latest-builds-json");
  if (!latestBuildsJsonPath) {
    throw new Error("ingest-paper-project requires --latest-builds-json <builds.json>");
  }
  const retrievedAt = readOption(args, "--retrieved-at") ?? new Date().toISOString();
  const root = findRepositoryRoot();
  const latest = getVersionDetail("java", readOption(args, "--java-latest") ?? "latest");
  const paper = buildPaperPluginData({
    projectJson: JSON.parse(readFileSync(projectJsonPath, "utf8")) as unknown,
    latestBuildsJson: JSON.parse(readFileSync(latestBuildsJsonPath, "utf8")) as unknown,
    javaLatest: latest.version,
    retrievedAt,
  });
  const output = join(root, "packages/data/data/java/paper.json");
  writeFileSync(output, `${JSON.stringify(paper, null, 2)}\n`);
  console.log(`wrote Paper plugin data to ${output}`);
}

