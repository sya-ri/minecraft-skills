#!/usr/bin/env node
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import {
  getCatalog,
  getVersionDetail,
  listDomains,
  listReferences,
} from "@minecraft-skills/catalog";

type ValidationResult = {
  ok: boolean;
  messages: string[];
};

const generatedHeader = "<!-- generated by @minecraft-skills/maintainer; do not edit directly -->";

function findRepositoryRoot(start = process.cwd()): string {
  let current = start;
  while (true) {
    if (existsSync(join(current, "pnpm-workspace.yaml"))) {
      return current;
    }
    const parent = dirname(current);
    if (parent === current) {
      throw new Error("Could not find repository root from current working directory");
    }
    current = parent;
  }
}

function requireFile(root: string, path: string, messages: string[]): void {
  if (!existsSync(join(root, path))) {
    messages.push(`missing file: ${path}`);
  }
}

function requireGeneratedHeader(root: string, path: string, messages: string[]): void {
  const absolutePath = join(root, path);
  requireFile(root, path, messages);
  if (existsSync(absolutePath) && !readFileSync(absolutePath, "utf8").includes(generatedHeader)) {
    messages.push(`missing generated header: ${path}`);
  }
}

export function validateRepository(): ValidationResult {
  const messages: string[] = [];
  const root = findRepositoryRoot();
  const catalog = getCatalog();

  if (catalog.supportPolicy.javaPrimarySince !== "1.13") {
    messages.push("Java primary support must start at 1.13");
  }

  for (const domain of listDomains()) {
    requireGeneratedHeader(root, `skills/${domain.skill}/SKILL.md`, messages);
  }

  for (const reference of listReferences()) {
    requireGeneratedHeader(root, reference.path, messages);
  }

  const latest = getVersionDetail("java", "latest");
  if (latest.coverage === "complete" && latest.packFormats.status !== "extracted") {
    messages.push("complete version coverage must include extracted pack formats");
  }

  return {
    ok: messages.length === 0,
    messages,
  };
}

function printHelp(): void {
  console.log(`minecraft-skills-maintainer

Usage:
  minecraft-skills-maintainer validate

Commands:
  validate  Validate checked-in data, catalog, and generated skills.`);
}

export function runMaintainerCli(argv: string[]): number {
  const [command] = argv;
  if (!command || command === "help" || command === "--help" || command === "-h") {
    printHelp();
    return 0;
  }

  if (command !== "validate") {
    console.error(`Unknown command: ${command}`);
    return 1;
  }

  const result = validateRepository();
  if (!result.ok) {
    for (const message of result.messages) {
      console.error(message);
    }
    return 1;
  }
  console.log("minecraft-skills repository validation passed");
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.exitCode = runMaintainerCli(process.argv.slice(2));
}
