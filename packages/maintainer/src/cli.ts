function validationSampleContent(
  domain: "datapack" | "resourcepack",
  path: string,
  detail: ReturnType<typeof getVersionDetail>,
): string | unknown {
  if (path.endsWith("pack.mcmeta")) {
    return {
      pack: {
        pack_format: domain === "datapack" ? detail.packFormats.data : detail.packFormats.resource,
        description: "minecraft-skills validation sample",
      },
    };
  }
  if (path.endsWith(".json")) {
    return {};
  }
  return "";
}

function validationClassKey(
  version: string,
  domain: "datapack" | "resourcepack",
  path: string,
): string {
  const normalized = path.replaceAll("\\", "/");
  const parts = normalized.split("/");
  if (path.endsWith("pack.mcmeta")) {
    return `${version}\t${domain}\tpack.mcmeta`;
  }
  if (normalized === "data/.mcassetsroot" || normalized === "assets/.mcassetsroot") {
    return `${version}\t${domain}\t.mcassetsroot`;
  }
  if (domain === "datapack") {
    const nestedDataIndex =
      parts[0] === "data" && parts[2] === "datapacks"
        ? parts.findIndex((part, index) => index > 2 && part === "data")
        : -1;
    const datapackParts = nestedDataIndex === -1 ? parts : parts.slice(nestedDataIndex);
    const top = datapackParts[2] ?? "";
    const second = datapackParts[3] ?? "";
    const extension = path.includes(".") ? (path.split(".").at(-1) ?? "") : "";
    const kind =
      top === "tags"
        ? `tag/${second}`
        : top === "worldgen"
          ? `worldgen/${second}`
          : top === "functions" || top === "function"
            ? "function"
            : top === "structures" || top === "structure"
              ? "structure"
              : top;
    return `${version}\t${domain}\t${kind}\t${extension}`;
  }
  const top = parts[2] ?? "";
  const second = parts[3] ?? "";
  const extension = path.includes(".") ? (path.split(".").at(-1) ?? "") : "";
  const kind =
    top === "models"
      ? "model"
      : top === "items"
        ? "item-definition"
        : top === "textures"
          ? `texture/${second}`
          : top === "shaders"
            ? `shader/${second}`
            : top === "sounds"
              ? "sound-asset"
              : top;
  return `${version}\t${domain}\t${kind}\t${extension}`;
}

function requirePackContentValidationSamples(root: string, messages: string[]): void {
  let checked = 0;
  const failures: string[] = [];
  const validationCache = new Map<string, true>();
  for (const version of listVersions("java")) {
    const detail = getVersionDetail("java", version.id);
    for (const domain of ["datapack", "resourcepack"] as const) {
      const pathIndex = join(root, dataFilePath(`java/vanilla-paths/${version.id}.${domain}.txt`));
      const paths = readFileSync(pathIndex, "utf8").trim().split(/\r?\n/).filter(Boolean);
      for (const path of paths) {
        checked += 1;
        const cacheKey = validationClassKey(version.id, domain, path);
        if (validationCache.has(cacheKey)) {
          continue;
        }
        const result = validatePackFileContent({
          version: version.id,
          domain,
          path,
          content: validationSampleContent(domain, path, detail),
        });
        if (!result.valid) {
          failures.push(
            `${version.id} ${domain} ${path}: ${result.issues
              .map((issue) => `${issue.keyword ?? "unknown"} ${issue.message}`)
              .join("; ")}`,
          );
          if (failures.length >= 50) {
            break;
          }
        } else {
          validationCache.set(cacheKey, true);
        }
      }
      if (failures.length >= 50) {
        break;
      }
    }
    if (failures.length >= 50) {
      break;
    }
  }
  if (checked === 0) {
    messages.push("pack content validation must check at least one vanilla path");
  }
  if (failures.length > 0) {
    messages.push(
      `pack content validation must pass for every bundled vanilla path; checked ${checked} before failing:\n${failures.join(
        "\n",
      )}`,
    );
  }
}

export function validateRepository(): ValidationResult {
  const messages: string[] = [];
  const root = findRepositoryRoot();
  const catalog = getCatalog();
  const javaVersions = listVersions("java");
  const paper = getPaperPluginData();
  const publicEntrypoints = collectPublicEntrypoints(root);

  requireDataManifestIntegrity(root, messages);
  requireSourcePolicyIntegrity(root, messages);
  requireDocumentationIntegrity(root, messages);
  requireFactSurfaces(root, publicEntrypoints, messages);
  requireAuthoringChecklists(root, publicEntrypoints, messages);
  requireAuthoringGuardrails(root, messages);
  requireAuthoringDiagnostics(root, publicEntrypoints, messages);
  requireAuthoringRecipes(root, publicEntrypoints, messages);
  requireAuthoringScenarios(root, messages);
  requireClaimPolicies(root, publicEntrypoints, messages);
  requireOutputRequirements(root, messages);
  requireResponsePatterns(root, messages);
  requireIntentLookups(root, publicEntrypoints, messages);
  requirePackContentValidationSamples(root, messages);

  if (catalog.supportPolicy.javaPrimarySince !== "1.13") {
    messages.push("Java primary support must start at 1.13");
  }

  if (catalog.latest.java !== javaVersions[0]?.id) {
    messages.push("catalog latest Java version must match bundled Java version index");
  }

  for (const domain of listDomains()) {
    const skillEntry = catalog.skills.find((skill) => skill.name === domain.skill);
    if (!skillEntry) {
      messages.push(`missing catalog skill entry for domain: ${domain.id}`);
    } else {
      if (skillEntry.domain !== domain.id) {
        messages.push(`catalog skill domain mismatch: ${skillEntry.name}`);
      }
      if (skillEntry.path !== `skills/${domain.skill}`) {
        messages.push(`catalog skill path mismatch: ${skillEntry.name}`);
      }
      if (skillEntry.skillFile !== `skills/${domain.skill}/SKILL.md`) {
        messages.push(`catalog skill SKILL.md path mismatch: ${skillEntry.name}`);
      }
      if (skillEntry.agentMetadata !== `skills/${domain.skill}/agents/openai.yaml`) {
        messages.push(`catalog skill agent metadata path mismatch: ${skillEntry.name}`);
      }
    }
    requireSkillMetadata(root, domain.skill, messages);
    requireSkillPayloadMirror(root, domain.skill, messages);
  }

  for (const reference of listReferences()) {
    requireGeneratedHeader(root, reference.path, messages);
    requireMirroredDataFile(root, reference.path, messages);
  }

  const latest = getVersionDetail("java", "latest");
  if (latest.coverage === "complete" && latest.packFormats.status !== "extracted") {
    messages.push("complete version coverage must include extracted pack formats");
  }

  for (const version of javaVersions) {
    const detail = getVersionDetail("java", version.id);
    const rawDetail = readJsonFile<ReturnType<typeof getVersionDetail>>(
      join(root, dataFilePath(`java/version-details/${version.id}.json`)),
    );
    const prefix = `java ${version.id}`;
    requireDataFile(root, `java/version-details/${version.id}.json`, messages);
    requireDataFile(root, `java/reports/${version.id}.json`, messages);
    requireDataFile(root, `java/command-paths/${version.id}.txt`, messages);
    requireDataFile(root, `java/registry-entries/${version.id}.tsv`, messages);
    requireDataFile(root, `java/vanilla-inventories/${version.id}.json`, messages);
    requireDataFile(root, `java/vanilla-paths/${version.id}.datapack.txt`, messages);
    requireDataFile(root, `java/vanilla-paths/${version.id}.resourcepack.txt`, messages);
    requireDataFile(root, `java/resourcepack-models/${version.id}.json`, messages);

    if (detail.coverage !== "version-json-and-jar") {
      messages.push(`${prefix} detail must have version-json-and-jar coverage`);
    }
    if (JSON.stringify(rawDetail.domains) !== JSON.stringify(detail.domains)) {
      messages.push(`${prefix} version detail must materialize derived domain coverage`);
    }
    if (
      detail.packFormats.status !== "extracted" ||
      detail.packFormats.data === null ||
      detail.packFormats.resource === null
    ) {
      messages.push(`${prefix} must have extracted data and resource pack formats`);
    }
    if (
      detail.domains.datapack.status !== "reports-extracted" ||
      detail.domains.datapack.unknowns.length > 0
    ) {
      messages.push(`${prefix} datapack coverage must include reports with no unknowns`);
    }
    if (
      detail.domains.resourcepack.status !== "models-extracted" ||
      detail.domains.resourcepack.unknowns.length > 0
    ) {
      messages.push(`${prefix} resourcepack coverage must include models with no unknowns`);
    }
  }

  for (const version of listPendingJavaReportVersions(root)) {
    messages.push(`java ${version} report summary or companion index needs repair`);
  }

  requireDataFile(root, `java/datapack-schema-surfaces/${catalog.latest.java}.json`, messages);
  try {
    getDatapackSchemaSurface("java", catalog.latest.java);
  } catch (error) {
    messages.push(
      `latest Java datapack schema surface must validate: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
  }

  for (const paperVersion of paper.versions) {
    const prefix = `paper ${paperVersion}`;
    const detail = getVersionDetail("java", paperVersion);
    const build = paper.versionBuilds.find(
      (candidate) => candidate.minecraftVersion === paperVersion,
    );
    if (!build) {
      messages.push(`${prefix} must have latest build metadata`);
    }
    if (detail.domains["paper-plugin"].status !== "api-reference-linked") {
      messages.push(`${prefix} must be linked from Java version details`);
    }
    const apiIndexPath = dataFilePath(`java/paper-api-indexes/${paperVersion}.json`);
    if (existsSync(join(root, apiIndexPath))) {
      if (
        !detail.domains["paper-plugin"].facts.includes(`paper_api_package_index=${paperVersion}`)
      ) {
        messages.push(`${prefix} must expose bundled Paper API package index fact`);
      }
      if (detail.domains["paper-plugin"].unknowns.length > 0) {
        messages.push(`${prefix} must not keep Paper API unknowns when package index is bundled`);
      }
    } else if (!detail.domains["paper-plugin"].unknowns.includes("server_api_changes")) {
      messages.push(`${prefix} must record server_api_changes when package index is unavailable`);
    }
  }

  requireDataFile(root, `java/paper-api-surfaces/${paper.latest.minecraftVersion}.json`, messages);
  try {
    getPaperApiSurface(paper.latest.minecraftVersion);
  } catch (error) {
    messages.push(
      `latest Paper API surface must validate: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
  }

  return {
    ok: messages.length === 0,
    messages,
  };
}

