function isDirectRun(metaUrl: string): boolean {
  return process.argv[1]
    ? realpathSync(fileURLToPath(metaUrl)) === realpathSync(process.argv[1])
    : false;
}

function findRepositoryRoot(start = process.cwd()): string {
  let current = start;
  while (true) {
    if (existsSync(join(current, "pnpm-workspace.yaml"))) {
      return current;
    }
    const parent = dirname(current);
    if (parent === current) {
      throw new Error("Could not find repository root from current working directory");
    }
    current = parent;
  }
}

function requireFile(root: string, path: string, messages: string[]): void {
  if (!existsSync(join(root, path))) {
    messages.push(`missing file: ${path}`);
  }
}

function dataFilePath(path: string): string {
  return `packages/data/data/${path}`;
}

function requireDataFile(root: string, path: string, messages: string[]): void {
  requireFile(root, dataFilePath(path), messages);
}

function readJsonFile<T>(path: string): T {
  return JSON.parse(readFileSync(path, "utf8")) as T;
}

function sha256File(path: string): string {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function versionFromJsonFileName(file: string): string | undefined {
  return file.endsWith(".json") ? file.slice(0, -".json".length) : undefined;
}

function buildDataManifestEntries(root: string, baseUrl: string): DataManifestEntry[] {
  const dataRoot = join(root, "packages/data/data");
  const sections: Array<{
    directory: string;
    kind: DataManifestEntry["kind"];
  }> = [
    {
      directory: "java/datapack-schema-surfaces",
      kind: "datapack-schema-surface",
    },
    {
      directory: "java/paper-api-surfaces",
      kind: "paper-api-surface",
    },
    {
      directory: "java/resourcepack-models",
      kind: "resourcepack-model-summary",
    },
  ];
  const normalizedBaseUrl = baseUrl.replace(/\/+$/, "");
  const entries: DataManifestEntry[] = [];

  for (const section of sections) {
    const absoluteDirectory = join(dataRoot, section.directory);
    if (!existsSync(absoluteDirectory)) {
      continue;
    }
    for (const file of readdirSync(absoluteDirectory).sort((left, right) =>
      left.localeCompare(right, undefined, { numeric: true }),
    )) {
      const version = versionFromJsonFileName(file);
      if (!version) {
        continue;
      }
      const path = `${section.directory}/${file}`;
      const absolutePath = join(dataRoot, path);
      entries.push({
        path,
        kind: section.kind,
        edition: "java",
        version,
        size: statSync(absolutePath).size,
        sha256: sha256File(absolutePath),
        url: `${normalizedBaseUrl}/${path}`,
      });
    }
  }

  return entries;
}

function writeDataManifest(root: string, dataVersion?: string, baseUrl?: string): string {
  const current = getDataManifest();
  const manifestBaseUrl = baseUrl ?? current.defaultBaseUrl;
  const manifest = {
    schemaVersion: 1,
    dataVersion: dataVersion ?? current.dataVersion,
    defaultBaseUrl: manifestBaseUrl,
    cache: current.cache,
    downloadable: buildDataManifestEntries(root, manifestBaseUrl),
  };
  const output = join(root, dataFilePath("data-manifest.json"));
  writeFileSync(output, `${JSON.stringify(manifest, null, 2)}\n`);
  return output;
}

function isSafeRelativePath(path: string): boolean {
  return path.length > 0 && !path.includes("\0") && !path.split(/[\\/]/).includes("..");
}

function requireDataManifestIntegrity(root: string, messages: string[]): void {
  requireDataFile(root, "data-manifest.json", messages);
  const manifestPath = join(root, dataFilePath("data-manifest.json"));
  if (!existsSync(manifestPath)) {
    return;
  }

  const manifest = getDataManifest();
  if (manifest.schemaVersion !== 1) {
    messages.push("data manifest schemaVersion must be 1");
  }
  if (manifest.cache.environmentVariable !== "MINECRAFT_SKILLS_CACHE_DIR") {
    messages.push("data manifest cache environment variable must be MINECRAFT_SKILLS_CACHE_DIR");
  }

  const seenPaths = new Set<string>();
  for (const entry of manifest.downloadable) {
    const prefix = `data manifest entry ${entry.path}`;
    if (!isSafeRelativePath(entry.path)) {
      messages.push(`${prefix} must use a safe relative path`);
      continue;
    }
    if (seenPaths.has(entry.path)) {
      messages.push(`${prefix} must not be duplicated`);
    }
    seenPaths.add(entry.path);

    if (entry.kind === "datapack-schema-surface") {
      if (entry.edition !== "java" || !entry.version) {
        messages.push(`${prefix} datapack schema surface must identify Java version`);
      } else if (entry.path !== `java/datapack-schema-surfaces/${entry.version}.json`) {
        messages.push(`${prefix} datapack schema surface path must match version`);
      }
    } else if (entry.kind === "paper-api-surface") {
      if (entry.edition !== "java" || !entry.version) {
        messages.push(`${prefix} Paper API surface must identify Java version`);
      } else if (entry.path !== `java/paper-api-surfaces/${entry.version}.json`) {
        messages.push(`${prefix} Paper API surface path must match version`);
      } else {
        const surface = readJsonFile<{
          typeCount?: unknown;
          memberCount?: unknown;
        }>(join(root, dataFilePath(entry.path)));
        if (surface.typeCount === 0 && surface.memberCount === 0) {
          messages.push(`${prefix} Paper API surface must not be empty`);
        }
      }
    } else if (entry.kind === "resourcepack-model-summary") {
      if (entry.edition !== "java" || !entry.version) {
        messages.push(`${prefix} resourcepack model summary must identify Java version`);
      } else if (entry.path !== `java/resourcepack-models/${entry.version}.json`) {
        messages.push(`${prefix} resourcepack model summary path must match version`);
      }
    } else {
      messages.push(`${prefix} has unsupported downloadable kind: ${entry.kind}`);
    }

    try {
      new URL(entry.url);
    } catch {
      messages.push(`${prefix} must include a valid URL`);
    }

    const absolutePath = join(root, dataFilePath(entry.path));
    requireDataFile(root, entry.path, messages);
    if (!existsSync(absolutePath)) {
      continue;
    }
    const actualSize = statSync(absolutePath).size;
    if (actualSize !== entry.size) {
      messages.push(
        `${prefix} size must match checked-in file: expected ${entry.size}, got ${actualSize}`,
      );
    }
    const actualSha256 = sha256File(absolutePath);
    if (actualSha256 !== entry.sha256) {
      messages.push(
        `${prefix} sha256 must match checked-in file: expected ${entry.sha256}, got ${actualSha256}`,
      );
    }
  }
}

function walkTextFiles(root: string, directory: string, files: string[] = []): string[] {
  const absoluteDirectory = join(root, directory);
  if (!existsSync(absoluteDirectory)) {
    return files;
  }
  for (const entry of readdirSync(absoluteDirectory)) {
    const path = join(directory, entry);
    const absolutePath = join(root, path);
    const stat = statSync(absolutePath);
    if (stat.isDirectory()) {
      if (
        path === ".git" ||
        path === "node_modules" ||
        path.endsWith("/dist") ||
        path === "packages/data/data/java"
      ) {
        continue;
      }
      walkTextFiles(root, path, files);
    } else if (/\.(?:md|json|ts|yaml|yml)$/.test(entry)) {
      files.push(path);
    }
  }
  return files;
}

function requireSourcePolicyIntegrity(root: string, messages: string[]): void {
  const sourcePolicy = getCatalog().sourcePolicy;
  if (sourcePolicy.minecraftWikiAutomation !== "forbidden") {
    messages.push("source policy must forbid Minecraft Wiki automation");
  }
  if (
    !sourcePolicy.prohibitedAutomation.some((rule) =>
      rule.includes("Do not fetch, crawl, summarize, or cite Minecraft Wiki pages"),
    )
  ) {
    messages.push("source policy must explicitly prohibit AI use of Minecraft Wiki pages");
  }
  for (const domain of getCatalog().domains) {
    for (const source of domain.primarySources) {
      if (source.url.includes("minecraft.wiki") || source.id.includes("minecraft-wiki")) {
        messages.push(`domain ${domain.id} must not expose Minecraft Wiki as a primary source`);
      }
      if (source.kind === "community-navigation") {
        messages.push(`domain ${domain.id} must not use community-navigation source kind`);
      }
    }
  }

  const requiredDatasetIds = new Set([
    "prismarinejs-minecraft-data",
    "prismarinejs-minecraft-assets",
    "inventivetalentdev-minecraft-assets",
    "misode-mcmeta",
  ]);
  const actualDatasetIds = new Set(
    sourcePolicy.recommendedCommunityDatasets.map((dataset) => dataset.id),
  );
  for (const id of requiredDatasetIds) {
    if (!actualDatasetIds.has(id)) {
      messages.push(`source policy must list recommended community dataset: ${id}`);
    }
  }

  const forbiddenPatterns = [
    /https?:\/\/(?:www\.)?minecraft\.wiki\b/i,
    /\bminecraft-wiki-(?:datapack|resourcepack|source|wiki)\b/i,
    /\bcommunity-navigation\b/i,
    /Minecraft Wiki may be used/i,
    /Use Minecraft Wiki (?!is human-only|pages are human-only)/i,
    /Minecraft Wiki is used only for/i,
    /navigation and provenance/i,
  ];
  for (const path of walkTextFiles(root, ".")) {
    if (path === "docs/SOURCE_STRATEGY.md" || path === "packages/maintainer/src/cli.ts") {
      continue;
    }
    const content = readFileSync(join(root, path), "utf8");
    for (const pattern of forbiddenPatterns) {
      if (pattern.test(content)) {
        messages.push(`forbidden Minecraft Wiki source wording in ${path}: ${pattern}`);
      }
    }
  }
}

function requireDocumentationIntegrity(root: string, messages: string[]): void {
  const packageJson = readJsonFile<{ version: string }>(join(root, "package.json"));
  const versionSupport = readFileSync(join(root, "docs/VERSION_SUPPORT.md"), "utf8");
  if (!versionSupport.includes(`minecraft-skills ${packageJson.version}`)) {
    messages.push("docs/VERSION_SUPPORT.md must reference the current workspace version");
  }

  const forbiddenSkillEntrypointPatterns = [
    /\bMCP\b/,
    /\bmcp\b/,
    /\bPackage API\b/,
    /\bpackage API\b/,
    /@minecraft-skills\/catalog/,
    /@minecraft-skills\/mcp/,
    /\b(?:get|list|search|compare)_[a-z_]+\b/,
  ];
  for (const domain of listDomains()) {
    const paths = [`skills/${domain.skill}/SKILL.md`];
    for (const reference of listReferences().filter((entry) => entry.domain === domain.id)) {
      paths.push(reference.path);
    }
    for (const path of paths) {
      const content = readFileSync(join(root, dataFilePath(path)), "utf8");
      for (const pattern of forbiddenSkillEntrypointPatterns) {
        if (pattern.test(content)) {
          messages.push(`skill-facing file must only document CLI entrypoints: ${path}`);
          break;
        }
      }
    }
  }
}

