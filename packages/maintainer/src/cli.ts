export async function runMaintainerCli(argv: string[]): Promise<number> {
  const [command] = argv;
  if (!command || command === "help" || command === "--help" || command === "-h") {
    printHelp();
    return 0;
  }

  try {
    if (command === "audit-current-sources") {
      const result = await auditCurrentSources();
      console.log(JSON.stringify(result, null, 2));
      return result.ok ? 0 : 1;
    }

    if (command === "package-smoke") {
      const result = runPackageSmoke({
        root: findRepositoryRoot(),
        keepTemp: argv.includes("--keep-temp"),
      });
      console.log(JSON.stringify(result, null, 2));
      return 0;
    }

    if (command === "write-data-manifest") {
      regenerateDataManifest(argv.slice(1));
      return 0;
    }

    if (command === "ingest-java-manifest") {
      ingestJavaManifest(argv.slice(1));
      return 0;
    }

    if (command === "ingest-java-version-detail") {
      ingestJavaVersionDetail(argv.slice(1));
      return 0;
    }

    if (command === "ingest-java-version-details") {
      await ingestAllJavaVersionDetails(argv.slice(1));
      return 0;
    }

    if (command === "ingest-java-reports") {
      ingestJavaReports(argv.slice(1));
      return 0;
    }

    if (command === "ingest-java-reports-all") {
      await ingestAllJavaReports(argv.slice(1));
      return 0;
    }

    if (command === "audit-java-reports") {
      const pendingVersions = listPendingJavaReportVersions(findRepositoryRoot());
      console.log(JSON.stringify({ ok: pendingVersions.length === 0, pendingVersions }, null, 2));
      return pendingVersions.length === 0 ? 0 : 1;
    }

    if (command === "generate-java-reports") {
      generateReports(argv.slice(1));
      return 0;
    }

    if (command === "ingest-paper-project") {
      ingestPaperProject(argv.slice(1));
      return 0;
    }

    if (command === "ingest-paper-builds") {
      await ingestAllPaperBuilds(argv.slice(1));
      return 0;
    }

    if (command === "ingest-paper-api-indexes") {
      await ingestAllPaperApiIndexes(argv.slice(1));
      return 0;
    }

    if (command === "ingest-paper-api-surfaces") {
      await ingestAllPaperApiSurfaces(argv.slice(1));
      return 0;
    }

    if (command === "materialize-version-details") {
      const root = findRepositoryRoot();
      const written = materializeVersionDetails(root);
      console.log(`wrote ${written} Java version detail files`);
      return 0;
    }

    if (command === "ingest-vanilla-inventory") {
      ingestVanillaInventory(argv.slice(1));
      return 0;
    }

    if (command === "ingest-vanilla-inventories") {
      await ingestAllVanillaInventories(argv.slice(1));
      return 0;
    }

    if (command === "ingest-datapack-schema") {
      ingestDatapackSchema(argv.slice(1));
      return 0;
    }

    if (command === "ingest-datapack-schemas-all") {
      await ingestAllDatapackSchemas(argv.slice(1));
      return 0;
    }

    if (command === "ingest-resourcepack-models") {
      ingestResourcepackModels(argv.slice(1));
      return 0;
    }

    if (command === "ingest-resourcepack-models-all") {
      await ingestAllResourcepackModels(argv.slice(1));
      return 0;
    }

    if (command !== "validate") {
      throw new Error(`Unknown command: ${command}`);
    }

    const result = validateRepository();
    if (!result.ok) {
      for (const message of result.messages) {
        console.error(message);
      }
      return 1;
    }
    console.log("minecraft-skills repository validation passed");
    return 0;
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    return 1;
  }
}

if (isDirectRun(import.meta.url)) {
  process.exitCode = await runMaintainerCli(process.argv.slice(2));
}
